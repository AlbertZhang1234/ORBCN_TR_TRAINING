interface PcI18nContextValue {
  lang: Lang;
  changeLanguage: (lang: Lang) => void;
  t: (key: string, fallback: string) => string;
}

const PcI18nContext = createContext<PcI18nContextValue | null>(null);

function getClientLang(): Lang {
  if (typeof window === 'undefined') {
    return 'en';
  }

  const stored = window.localStorage.getItem('pc_lang');
  if (stored === 'zh' || stored === 'en') {
    return stored;
  }

  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en';
}

export function PcI18nProvider({ children }: PropsWithChildren): ReactNode {
  const [lang, setLang] = useState<Lang>('en');
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setLang(getClientLang());
    setMounted(true);
  }, []);

  useEffect(() => {
    document.documentElement.lang = lang === 'zh' ? 'zh-CN' : 'en';
  }, [lang]);

  const changeLanguage = (newLang: Lang) => {
    setLang(newLang);
    if (typeof window !== 'undefined') {
      window.localStorage.setItem('pc_lang', newLang);
    }
  };

  const t = (key: string, fallback: string): string => {
    return dict[lang]?.[key] ?? fallback;
  };

  if (!mounted) {
    return null; // or a loading spinner
  }

  return (
    <PcI18nContext.Provider value={{ lang, changeLanguage, t }}>
      {children}
    </PcI18nContext.Provider>
  );
}

export function usePcI18n() {
  const context = useContext(PcI18nContext);
  if (!context) {
    throw new Error('usePcI18n must be used within a PcI18nProvider');
  }
  return context;
}
